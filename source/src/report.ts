import type { Finding, Severity } from "./types.js";
import type { Dataset, CheckResult } from "./sections.js";
import { CATEGORY } from "./sections.js";
import { PRIORITIES, PRIORITY_LABEL } from "./triage.js";

const ORDER: Severity[] = ["critical", "warning", "info"];
const LABEL: Record<Severity, string> = { critical: "CRITICAL", warning: "WARNING", info: "INFO" };
const COLOR: Record<Severity, string> = { critical: "\x1b[31m", warning: "\x1b[33m", info: "\x1b[36m" };

/** Triaged findings are already in the order to fix them; untriaged ones are sorted by severity. */
export function sortFindings(f: Finding[]): Finding[] {
  if (f.length && f.every((x) => x.priority)) return [...f];
  return [...f].sort((a, b) => ORDER.indexOf(a.severity) - ORDER.indexOf(b.severity));
}
const groups = (fs: Finding[]) => PRIORITIES.map((p) => ({ p, label: PRIORITY_LABEL[p], items: fs.filter((f) => (f.priority ?? "watch") === p) })).filter((g) => g.items.length);

export function toText(findings: Finding[], color = true): string {
  const c = (s: Severity, t: string) => (color ? `${COLOR[s]}${t}\x1b[0m` : t);
  if (!findings.length) return "No problems found. ✓";
  const lines: string[] = [];
  const counts = ORDER.map((s) => `${findings.filter((f) => f.severity === s).length} ${s}`).join(", ");
  lines.push(`pg-checkup: ${counts}\n`);
  for (const g of groups(sortFindings(findings))) {
    lines.push(`== ${g.label} ==\n`);
    for (const f of g.items) {
      lines.push(`${c(f.severity, `[${LABEL[f.severity]}]`)} ${f.title}  (${f.category})`);
      if (f.note) lines.push(`  Note: ${f.note}`);
      lines.push(`  Why:  ${f.why}`);
      lines.push(`  Fix:  ${f.fix}\n`);
    }
  }
  return lines.join("\n");
}

export interface ReportMeta { version?: string; provider?: string | null; scannedAt?: number | string; checks?: CheckResult[] }
const DOT: Record<Severity, string> = { critical: "\u{1F534}", warning: "\u{1F7E0}", info: "\u{1F535}" };
const STATE: Record<string, string> = { passed: "\u2705 Passed", flagged: "\u26A0\uFE0F Flagged", skipped: "\u2796 Skipped", na: "\u00B7 N/A" };
const esc = (v: unknown, n = 120) => String(v ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").slice(0, n);

/** A shareable report: metadata, summary, ranked findings with fixes, every check's result, then the data. */
export function toMarkdown(findings: Finding[], datasets: Dataset[] = [], meta: ReportMeta = {}): string {
  const sorted = sortFindings(findings);
  const n = (s: Severity) => findings.filter((f) => f.severity === s).length;
  const active = (meta.checks ?? []).filter((c) => c.status !== "na");
  const passed = active.filter((c) => c.status === "passed").length;
  const when = meta.scannedAt ? new Date(meta.scannedAt).toISOString().replace("T", " ").slice(0, 16) + " UTC" : "";
  const out: string[] = ["# Postgres health report", ""];
  const facts = [meta.version && `**Server:** ${meta.version}${meta.provider && meta.provider !== "generic" ? ` (${meta.provider})` : ""}`, when && `**Scanned:** ${when}`].filter(Boolean);
  if (facts.length) out.push(facts.join("  \u00B7  "), "");
  out.push("## Summary", "", "| Critical | Warning | Info | Checks passed |", "|:-:|:-:|:-:|:-:|", `| ${n("critical")} | ${n("warning")} | ${n("info")} | ${active.length ? `${passed} / ${active.length}` : "-"} |`, "");
  out.push(`## Findings (${findings.length})`, "");
  if (!sorted.length) out.push("No problems found. \u2705", "");
  for (const g of groups(sorted)) {
    out.push(`### ${g.label}`, "");
    for (const f of g.items) {
      out.push(`#### ${DOT[f.severity]} ${f.title}`, "", `**Severity:** ${f.severity}  \u00B7  **Area:** ${f.category}`, "", ...(f.note ? [`**First:** ${f.note}`, ""] : []), `**Why it matters:** ${f.why}`, "", `**How to fix:** ${f.fix}`, "", ...(f.sql ? ["```sql", f.sql.trimEnd(), "```", ""] : []));
      if (f.evidence) out.push("<details><summary>Evidence</summary>", "", "```json", JSON.stringify(f.evidence, null, 2), "```", "", "</details>", "");
    }
  }
  if (active.length) {
    out.push("## All checks", "", "| Result | Area | Check |", "|---|---|---|");
    for (const c of active) out.push(`| ${STATE[c.status]} | ${CATEGORY[c.section]} | ${esc(c.title)}${c.reason && c.status !== "flagged" ? ` \u2014 ${esc(c.reason, 90)}` : ""} |`);
    out.push("");
  }
  const shown = datasets.filter((d) => d.rows.length);
  if (shown.length) out.push("## Data", "");
  for (const d of shown) {
    const cols = d.columns.filter((c) => d.rows.some((row) => row[c.key] !== null && row[c.key] !== undefined));
    out.push(`### ${d.title}`, `*Source: ${d.source}*`, "", `| ${cols.map((c) => c.label).join(" | ")} |`, `| ${cols.map(() => "---").join(" | ")} |`);
    for (const row of d.rows.slice(0, 25)) out.push(`| ${cols.map((c) => esc(row[c.key])).join(" | ")} |`);
    out.push("");
  }
  out.push("---", "*Generated by pg-checkup. Read-only checks; no table contents were read.*", "");
  return out.join("\n");
}
